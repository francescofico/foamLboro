# Validation
# ----------------------------------------------------------------------------
def validate(case, title, tol, conducting):
    from mhdAnalytic import BuoyantDuctSolution

    par = read_parameters(case/"system"/"caseParameters")
    Ha, heating = par["Ha"], par["heating"]
    F, slope = forcing_amplitude(par)
    forcing = "y" if heating == "parallel" else "z"
    if conducting:
        ref = BuoyantDuctSolution(Ha, forcing, "thick", sigma_ratio=par["sigmaRatio"],
                                  thickness=par["wallThickness"])
    else:
        ref = BuoyantDuctSolution(Ha, forcing, "insulating")

    times = [t for t in time_dirs(case) if t.name != "0"]
    t, tp = times[-1], (times[-2] if len(times) > 1 else None)
    sub = (lambda d: d/"fluid") if conducting else (lambda d: d)
    C = read_internal_field(sub(t)/"C")
    n = len(C)
    V = read_internal_field(sub(t)/"V", n)
    U = read_internal_field(sub(t)/"U", n)
    T = read_internal_field(sub(t)/"T", n)
    P = read_internal_field(sub(t)/"PotE", n)
    y, z, u = C[:, 1], C[:, 2], U[:, 0]
    ua = F*ref.velocity(y, z)
    pa = Ha*F*ref.potential(y, z)
    pn = P - (P*V).sum()/V.sum()
    Ta = slope*(y if forcing == "y" else z)
    umax = np.abs(ua).max()
    e_u = np.abs(u - ua).max()/umax
    e_l2 = np.sqrt(((u - ua)**2*V).sum()/(ua**2*V).sum())
    e_p = np.abs(pn - pa).max()/np.abs(pa).max()
    e_T = np.abs(T - Ta).max()/0.5
    drift = np.abs(u - read_internal_field(sub(tp)/"U", n)[:, 0]).max()/umax if tp else 0.0

    print(f"\n{title}, time {t.name}, {n} fluid cells")
    print(f"grad T {heating} to B: fluid T = {slope:g} {forcing}, body force {F:g} {forcing}\n")
    ok = report([("u_max (upward)", u.max(), ua.max()),
                 ("u_min (downward)", u.min(), ua.min())], tol)
    rows = [("velocity error (max, rel. to |u|max)", e_u, True),
            ("velocity error (L2, relative)", e_l2, False),
            ("potential error (max, rel.)", e_p, True),
            ("temperature error (max, rel. to dT/2)", e_T, True),
            ("change over the last write interval", drift, "steady")]

    wall = None
    if conducting:
        Cs = read_internal_field(t/"solid"/"C")
        Ps = read_internal_field(t/"solid"/"PotE", len(Cs))
        Ts = read_internal_field(t/"solid"/"T", len(Cs))
        ps = Ps - (P*V).sum()/V.sum()
        ys, zs = Cs[:, 1], Cs[:, 2]
        ymid = ys[ys > 0][np.argmin(np.abs(ys[ys > 0] - (1 + par["wallThickness"]/2)))]
        sel = np.isclose(ys, ymid)
        pw = Ha*F*ref.wall_potential(ys[sel], zs[sel])
        e_w = np.abs(ps[sel] - pw).max()/np.abs(pw).max()
        if heating == "parallel":
            # linear in each wall: T at the interface y = +-1 is slope*(+-1)
            tw = par["wallThickness"]
            Tsa = np.sign(ys)*(slope + (-0.5 - slope)*(np.abs(ys) - 1.0)/tw)
        else:
            Tsa = -0.5*zs
        e_Ts = np.abs(Ts - Tsa).max()/0.5
        rows += [("wall potential error (max, rel.)", e_w, True),
                 ("wall temperature error (max, rel.)", e_Ts, True)]
        wall = (zs[sel], ps[sel], pw, ymid)

    for name, val, tested in rows:
        lim = 0.1*tol if tested == "steady" else tol     # steadiness: as in the duct cases
        flag = "  <-- above tolerance" if tested and val > lim else ""
        print(f"{name:42s} {val:12.3e}{flag}")
        if tested:
            ok = ok and val <= lim

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        s = np.linspace(-1, 1, 801)
        i = np.argmax(np.abs(ua))
        y0, z0 = y[i], z[i]
        fig, ax = plt.subplots(2, 2, figsize=(11, 8.5))
        r = np.isclose(y, y0)
        o = np.argsort(z[r])
        ax[0, 0].plot(s, F*ref.velocity(np.full_like(s, y0), s), "k-", label="exact")
        ax[0, 0].plot(z[r][o], u[r][o], "o", ms=3, mfc="none", label="OpenFOAM")
        ax[0, 0].set(xlabel="z / a", ylabel="u", title=f"normal to B, y = {y0:.3g}")
        ax[0, 0].legend()
        c = np.isclose(z, z0)
        o = np.argsort(y[c])
        ax[0, 1].plot(s, F*ref.velocity(s, np.full_like(s, z0)), "k-")
        ax[0, 1].plot(y[c][o], u[c][o], "o", ms=3, mfc="none")
        ax[0, 1].set(xlabel="y / a", ylabel="u", title=f"along B, z = {z0:.3g}")
        if wall is not None:
            zw, pnw, paw, ymid = wall
            o = np.argsort(zw)
            ax[1, 0].plot(zw[o], paw[o], "k-", label="exact")
            ax[1, 0].plot(zw[o], pnw[o], "o", ms=3, mfc="none", label="OpenFOAM (solid)")
            ax[1, 0].set(xlabel="z / a", ylabel="PotE", title=f"wall potential, y = {ymid:.3g}")
        else:
            o = np.argsort(z[r])
            ax[1, 0].plot(s, Ha*F*ref.potential(np.full_like(s, y0), s), "k-")
            ax[1, 0].plot(z[r][o], pn[r][o], "o", ms=3, mfc="none")
            ax[1, 0].set(xlabel="z / a", ylabel="PotE", title=f"potential, y = {y0:.3g}")
        sc = ax[1, 1].tricontourf(z, y, u, 30, cmap="RdBu_r")
        fig.colorbar(sc, ax=ax[1, 1], label="u (vertical)")
        ax[1, 1].set(xlabel="z / a", ylabel="y / a", title="OpenFOAM velocity (B along y)", aspect="equal")
        fig.suptitle(title + f", grad T {heating} to B")
        fig.tight_layout()
        fig.savefig(case/"validation.png", dpi=130)
        print("\nWrote validation.png")
    except ImportError:
        pass
    print("\nPASS" if ok else "\nFAIL")
    sys.exit(0 if ok else 1)
