"""Setup and validation for fully developed buoyant flow in a vertical square
duct with differentially heated walls and a transverse field (B along y).
Shared by epotFoamBuo/buoyant_duct_insulating and
cEpotBuoyantFoam/buoyant_duct_conducting.

x is vertical and periodic with one cell. A periodic p_rgh cannot carry
buoyancy along the periodic direction, so gravity is set to zero and the
Boussinesq force Gr (T - TRef) e_x is added by a coded fvOption that setup.py
generates.

Heating orientations:
    parallel : grad T along B.  Hartmann walls (y = -/+1) hot/cold. Forcing f ~ y.
    normal   : grad T normal to B. Side walls (z = -/+1) hot/cold. Forcing f ~ z.

Conducting case: solid slabs 1 < |y| < 1 + t on the Hartmann walls, as in
hunt_duct. For "parallel" the outer slab faces carry the hot and cold
temperatures, and the heat crosses the walls; the slab ends are adiabatic.
For "normal" the slab ends carry the same temperatures as the side walls and
the outer faces are adiabatic, so T = -z/2 everywhere.
"""
import argparse
import sys

import numpy as np

from foamCase import (HEADER, expansion, read_internal_field, read_parameters,
                      report, symmetric_grading, time_dirs, write_parameters)

L = 0.05
BAN = r"""/*--------------------------------*- C++ -*----------------------------------*\
| Generated by setup.py - edit the script, not this file                  |
\*---------------------------------------------------------------------------*/
"""
END = "\n// ************************************************************************* //\n"


def _foamfile(cls, loc, obj):
    return BAN + f"""FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def parse(case, description, defaults, conducting):
    old = read_parameters(case/"system"/"caseParameters")
    get = lambda k: old.get(k, defaults[k])
    p = argparse.ArgumentParser(description=description,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--ha", type=float, default=get("Ha"), help="Hartmann number")
    p.add_argument("--gr", type=float, default=get("Gr"), help="Grashof number g beta dT a^3/nu^2")
    p.add_argument("--pr", type=float, default=get("Pr"), help="Prandtl number")
    p.add_argument("--heating", choices=("parallel", "normal"), default=get("heating"),
                   help="grad T parallel or normal to B")
    p.add_argument("--cells", type=int, default=int(get("cellsHalf")), help="cells per half-width")
    p.add_argument("--layer-cells", type=float, default=get("layerCells"))
    p.add_argument("--side-cells", type=float, default=get("sideCells"))
    if conducting:
        p.add_argument("--thickness", type=float, default=get("wallThickness"), help="t_w/a")
        p.add_argument("--sigma-ratio", type=float, default=get("sigmaRatio"), help="sigma_w/sigma")
        p.add_argument("--k-ratio", type=float, default=get("kRatio"), help="thermal conductivity k_w/k")
        p.add_argument("--wall-cells", type=int, default=int(get("wallCells")))
    a = p.parse_args()
    a.conducting = conducting
    return a


def forcing_amplitude(par):
    """F such that the body force is F*y ("parallel") or F*z ("normal"), and the
    fluid temperature T(y) or T(z), for the parameters in caseParameters."""
    Gr = par["Gr"]
    if par["heating"] == "normal":
        slope = -0.5                                   # T = -z/2
    elif "wallThickness" in par:
        t, kr = par["wallThickness"], par["kRatio"]
        slope = -1.0/(2.0 + 2.0*t/kr)                  # series resistance: walls + fluid
    else:
        slope = -0.5
    return Gr*slope, slope


# ----------------------------------------------------------------------------
# Writing the case
# ----------------------------------------------------------------------------
def _fluid_blockmesh(a, ny, gy, nz, gz):
    if a.conducting:
        def hart(name, side, face):
            return f"""    fluid_to_solid_{side}{" " * (8 - len(side))}// {name}
    {{
        type            mappedWall;
        sampleMode      nearestPatchFace;
        sampleRegion    solid;
        samplePatch     solid_to_fluid_{side};
        offsetMode      uniform;
        offset          (0 0 0);
        faces           ({face});
    }}"""
        h = hart("y = -1", "bottom", "(0 1 5 4)") + "\n" + hart("y = +1", "top", "(3 7 6 2)")
    else:
        h = """    hartmannBottom              // y = -1
    {
        type wall;
        faces ((0 1 5 4));
    }
    hartmannTop                 // y = +1
    {
        type wall;
        faces ((3 7 6 2));
    }"""
    return HEADER.format(script="setup.py") + f"""
scale 1;

// Fluid: vertical square duct -1 < y, z < 1 (B along y), x vertical, periodic.
vertices
(
    (0  -1 -1) ({L} -1 -1) ({L} 1 -1) (0 1 -1)
    (0  -1  1) ({L} -1  1) ({L} 1  1) (0 1  1)
);

blocks
(
    hex (0 1 2 3 4 5 6 7) (1 {ny} {nz}) simpleGrading (1 {gy} {gz})
);

boundary
(
{h}
    sideMinus                   // z = -1
    {{
        type wall;
        faces ((0 3 2 1));
    }}
    sidePlus                    // z = +1
    {{
        type wall;
        faces ((4 5 6 7));
    }}
    xPeriodic0
    {{
        type cyclic;
        neighbourPatch xPeriodic1;
        faces ((0 4 7 3));
    }}
    xPeriodic1
    {{
        type cyclic;
        neighbourPatch xPeriodic0;
        faces ((1 2 6 5));
    }}
);

// ************************************************************************* //
"""


def _solid_blockmesh(a, nz, gz, first):
    t, nw = a.thickness, a.wall_cells
    ew = expansion(t, nw, min(first, t/nw))
    T = 1.0 + t
    return HEADER.format(script="setup.py") + f"""
scale 1;

// Solid: two slabs 1 < |y| < {T:g} on the Hartmann walls; z grading matches the fluid.
vertices
(
    (0 {-T} -1) ({L} {-T} -1) ({L} -1 -1) (0 -1 -1)
    (0 {-T}  1) ({L} {-T}  1) ({L} -1  1) (0 -1  1)
    (0 1 -1) ({L} 1 -1) ({L} {T} -1) (0 {T} -1)
    (0 1  1) ({L} 1  1) ({L} {T}  1) (0 {T}  1)
);

blocks
(
    hex (0 1 2 3 4 5 6 7)         (1 {nw} {nz}) simpleGrading (1 {1.0/ew:.10g} {gz})
    hex (8 9 10 11 12 13 14 15)   (1 {nw} {nz}) simpleGrading (1 {ew:.10g} {gz})
);

boundary
(
    solid_to_fluid_bottom
    {{
        type            mappedWall;
        sampleMode      nearestPatchFace;
        sampleRegion    fluid;
        samplePatch     fluid_to_solid_bottom;
        offsetMode      uniform;
        offset          (0 0 0);
        faces           ((3 7 6 2));
    }}
    solid_to_fluid_top
    {{
        type            mappedWall;
        sampleMode      nearestPatchFace;
        sampleRegion    fluid;
        samplePatch     fluid_to_solid_top;
        offsetMode      uniform;
        offset          (0 0 0);
        faces           ((8 9 13 12));
    }}
    outerBottom                 // y = -{T:g}
    {{
        type wall;
        faces ((0 1 5 4));
    }}
    outerTop                    // y = +{T:g}
    {{
        type wall;
        faces ((11 15 14 10));
    }}
    endsMinus                   // z = -1 ends of both slabs
    {{
        type wall;
        faces ((0 3 2 1) (8 11 10 9));
    }}
    endsPlus                    // z = +1 ends of both slabs
    {{
        type wall;
        faces ((4 5 6 7) (12 13 14 15));
    }}
    xPeriodic0
    {{
        type cyclic;
        neighbourPatch xPeriodic1;
        faces ((0 4 7 3) (8 12 15 11));
    }}
    xPeriodic1
    {{
        type cyclic;
        neighbourPatch xPeriodic0;
        faces ((1 2 6 5) (9 10 14 13));
    }}
);

// ************************************************************************* //
"""


def _bc(kind, value=None):
    if kind == "fixed":
        return f"type            fixedValue;\n        value           uniform {value};"
    if kind == "adiabatic":
        return "type            zeroGradient;"
    if kind == "coupled":
        return ("type            solidWallMixedTemperatureCoupled;\n"
                "        value           uniform 0;\n"
                "        Tnbr            T;\n"
                "        K               K;")
    raise ValueError(kind)


def _T_field(loc, patches, note):
    body = "\n".join(f"    {name}\n    {{\n        {_bc(*spec)}\n    }}" for name, spec in patches)
    return (_foamfile("volScalarField", loc, "T") + f"""// {note}
// Generated by setup.py for the chosen heating orientation.
dimensions      [0 0 0 1 0 0 0];

internalField   uniform 0;

boundaryField
{{
{body}
    "xPeriodic.*"
    {{
        type            cyclic;
    }}
}}
""" + END)


def _fvoptions(loc, Gr, mean_velocity=False):
    return (_foamfile("dictionary", loc, "fvOptions") + f"""// Boussinesq buoyancy as an explicit body force, F_x = Gr (T - TRef), TRef = 0.
// x is vertical and periodic, so the solver's own p_rgh buoyancy cannot drive
// a streamwise flow; constant/g is set to zero. Gr is written by setup.py.
boussinesqBuoyancy
{{
    type            vectorCodedSource;
    selectionMode   all;
    fields          (U);
    name            boussinesqBuoyancy;

    codeCorrect
    #{{
    #}};

    codeConstrain
    #{{
    #}};

    codeAddSup
    #{{
        const volScalarField& T = mesh_.lookupObject<volScalarField>("T");
        const scalarField& V = mesh_.V();
        vectorField& Usource = eqn.source();
        const scalar Gr = {Gr:.12g};
        forAll(V, celli)
        {{
            // eqn.source() -= S*V adds +S to the momentum equation
            Usource[celli].x() -= Gr*T[celli]*V[celli];
        }}
    #}};
}}
""" + ("""
// Mixed convection: the bulk velocity is held at ubar = 1 by a uniform
// pressure gradient, logged as "pressure gradient = ...".
momentumSource
{
    type            meanVelocityForce;
    selectionMode   all;
    fields          (U);
    Ubar            (1 0 0);
}
""" if mean_velocity else "") + END)


def write(case, a, title, mean_velocity=False, extra_entries=()):
    Ha = a.ha
    dt = 0.25/Ha**2
    # Insulating walls: the flow settles with an e-folding time of ~1/Ha and
    # is steady to 1e-7 by ~10/Ha. Conducting walls settle by ~5/Ha.
    end = (5.0 if a.conducting else 10.0)/Ha
    ny, gy = symmetric_grading(a.cells, 1.0/(Ha*a.layer_cells))
    nz, gz = symmetric_grading(a.cells, 1.0/(Ha**0.5*a.side_cells))
    first = 1.0/(Ha*a.layer_cells)
    entries = [
        ("Ha", Ha, "Hartmann number B a sqrt(sigma/(rho nu)); a = rho = nu = sigma = 1"),
        ("B", Ha, "applied field magnitude (= Ha in these units)"),
        ("Gr", a.gr, "Grashof number g beta dT a^3/nu^2 (dT = beta = 1)"),
        ("Pr", a.pr, "Prandtl number; thermal diffusivity kappa = 1/Pr"),
        ("kappa", 1.0/a.pr, "fluid thermal diffusivity"),
        ("heating", a.heating, "parallel (grad T along B) | normal (grad T normal to B)"),
    ]
    sysdir = case/"system"
    if a.conducting:
        (sysdir/"fluid"/"blockMeshDict").write_text(_fluid_blockmesh(a, ny, gy, nz, gz))
        (sysdir/"solid"/"blockMeshDict").write_text(_solid_blockmesh(a, nz, gz, first))
        entries += [
            ("wallThickness", a.thickness, "t_w / a"),
            ("sigmaRatio", a.sigma_ratio, "sigma_w / sigma"),
            ("sigmaWall", a.sigma_ratio, "sigma_w"),
            ("kRatio", a.k_ratio, "k_w / k (thermal conductivity, fluid k = 1)"),
            ("kWall", a.k_ratio, "k_w"),
            ("kappaWall", 1.0/a.pr, "solid thermal diffusivity (only sets the time scale)"),
            ("wallCells", float(a.wall_cells), ""),
        ]
        par = dict(Gr=a.gr, heating=a.heating, wallThickness=a.thickness, kRatio=a.k_ratio)
        if a.heating == "parallel":
            fluid = [("fluid_to_solid_bottom", ("coupled",)), ("fluid_to_solid_top", ("coupled",)),
                     ("sideMinus", ("adiabatic",)), ("sidePlus", ("adiabatic",))]
            solid = [("solid_to_fluid_bottom", ("coupled",)), ("solid_to_fluid_top", ("coupled",)),
                     ("outerBottom", ("fixed", 0.5)), ("outerTop", ("fixed", -0.5)),
                     ("endsMinus", ("adiabatic",)), ("endsPlus", ("adiabatic",))]
            note = "grad T along B: outer faces of the Hartmann walls hot (y < 0) and cold."
        else:
            fluid = [("fluid_to_solid_bottom", ("coupled",)), ("fluid_to_solid_top", ("coupled",)),
                     ("sideMinus", ("fixed", 0.5)), ("sidePlus", ("fixed", -0.5))]
            solid = [("solid_to_fluid_bottom", ("coupled",)), ("solid_to_fluid_top", ("coupled",)),
                     ("outerBottom", ("adiabatic",)), ("outerTop", ("adiabatic",)),
                     ("endsMinus", ("fixed", 0.5)), ("endsPlus", ("fixed", -0.5))]
            note = "grad T normal to B: side walls (and slab ends) hot at z = -1, cold at z = +1."
        (case/"0"/"fluid"/"T").write_text(_T_field("0/fluid", fluid, note))
        (case/"0"/"solid"/"T").write_text(_T_field("0/solid", solid, note))
        (case/"constant"/"fluid"/"fvOptions").write_text(_fvoptions("constant/fluid", a.gr, mean_velocity))
    else:
        (sysdir/"blockMeshDict").write_text(
            _fluid_blockmesh(a, ny, gy, nz, gz))
        par = dict(Gr=a.gr, heating=a.heating)
        if a.heating == "parallel":
            fluid = [("hartmannBottom", ("fixed", 0.5)), ("hartmannTop", ("fixed", -0.5)),
                     ("sideMinus", ("adiabatic",)), ("sidePlus", ("adiabatic",))]
            note = "grad T along B: Hartmann wall y = -1 hot, y = +1 cold; side walls adiabatic."
        else:
            fluid = [("hartmannBottom", ("adiabatic",)), ("hartmannTop", ("adiabatic",)),
                     ("sideMinus", ("fixed", 0.5)), ("sidePlus", ("fixed", -0.5))]
            note = "grad T normal to B: side wall z = -1 hot, z = +1 cold; Hartmann walls adiabatic."
        (case/"0"/"T").write_text(_T_field("0", fluid, note))
        (case/"constant"/"fvOptions").write_text(_fvoptions("constant", a.gr, mean_velocity))
    F, slope = forcing_amplitude(par)
    entries += [
        ("forcing", F, "body force F*y (parallel) or F*z (normal) in the fluid"),
        ("deltaT", dt, "0.25/Ha^2 (explicit Lorentz force)"),
        ("endTime", end, "5/Ha (conducting) or 10/Ha (insulating)"),
        ("writeInterval", end/10, "the last two writes are kept for the steadiness check"),
        ("cellsHalf", float(a.cells), ""),
        ("layerCells", float(a.layer_cells), ""),
        ("sideCells", float(a.side_cells), ""),
    ] + list(extra_entries)
    write_parameters(sysdir/"caseParameters", "setup.py", entries,
                     [f"{title} parameters. Regenerate with: python3 setup.py --ha <Ha> --heating <parallel|normal>"])
    print(f"Ha = {Ha:g}, Gr = {a.gr:g}, heating {a.heating} to B, fluid T slope {slope:g}, "
          f"forcing F = {F:g}; fluid {ny} x {nz}; deltaT = {dt:.3g}, endTime = {end:.3g} ({end/dt:.0f} steps)")


