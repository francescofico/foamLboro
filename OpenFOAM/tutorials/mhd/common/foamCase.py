"""Small helpers shared by the validation tutorials: blockMesh grading,
ASCII field reading and log parsing. It needs only numpy."""
import re
from pathlib import Path

import numpy as np

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
| Generated by {script} - edit the script, not this file                  |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      blockMeshDict;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
"""


# ----------------------------------------------------------------------------
# Case parameter file (system/caseParameters)
# ----------------------------------------------------------------------------
PARAM_HEADER = HEADER.replace("blockMeshDict", "caseParameters")


def read_parameters(path):
    """Read simple 'key value;' entries into a dict of floats or strings."""
    out = {}
    p = Path(path)
    if not p.exists():
        return out
    for key, val in re.findall(r"^\s*(\w+)\s+([^;]+);", p.read_text(), re.M):
        if key == "FoamFile" or val.strip().startswith("{"):
            continue
        try:
            out[key] = float(val)
        except ValueError:
            out[key] = val.strip()
    return out


def write_parameters(path, script, entries, notes):
    """Write system/caseParameters. `entries` is a list of (key, value, comment)."""
    lines = [PARAM_HEADER.format(script=script)]
    lines += [f"// {n}" for n in notes] + [""]
    for key, val, comment in entries:
        v = f"{val:.12g}" if isinstance(val, float) else str(val)
        lines.append(f"{key:<16s}{v};" + (f"  // {comment}" if comment else ""))
    lines.append("\n// ************************************************************************* //\n")
    Path(path).write_text("\n".join(lines))


# ----------------------------------------------------------------------------
# Mesh grading
# ----------------------------------------------------------------------------
def expansion(length, n, first):
    """blockMesh expansion ratio (last/first) for n cells over `length`
    with first-cell size `first`. Returns 1 if a uniform mesh is fine enough."""
    if first*n >= length:
        return 1.0
    lo, hi = 1.0 + 1e-12, 2.0
    while first*(hi**n - 1)/(hi - 1) < length:
        hi *= 2
    for _ in range(200):                       # bisection on the cell-to-cell ratio
        r = 0.5*(lo + hi)
        if first*(r**n - 1)/(r - 1) > length:
            hi = r
        else:
            lo = r
    return r**(n - 1)


def symmetric_grading(n_half, first, half_length=1.0):
    """Two-sided grading towards both ends of a block of length 2*half_length.
    Returns (cells, grading-string)."""
    e = expansion(half_length, n_half, first)
    return 2*n_half, f"((0.5 0.5 {e:.10g}) (0.5 0.5 {1.0/e:.10g}))"


def graded_from_wall(n, first, length, towards_end=False):
    """One-sided grading: fine at the start (or at the end if towards_end)."""
    e = expansion(length, n, first)
    return n, f"{(1.0/e if towards_end else e):.10g}"


# ----------------------------------------------------------------------------
# Reading OpenFOAM ASCII output
# ----------------------------------------------------------------------------
def time_dirs(path):
    out = []
    for p in Path(path).iterdir():
        try:
            out.append((float(p.name), p))
        except ValueError:
            pass
    return [p for _, p in sorted(out)]


def latest_time(case):
    dirs = [p for p in time_dirs(case) if p.name != "0"]
    if not dirs:
        raise FileNotFoundError(f"No solution time directories in {case}")
    return dirs[-1]


def read_internal_field(path, n_cells=None):
    """Return the internalField of an ASCII vol field as an (n,) or (n,3) array."""
    text = Path(path).read_text()
    m = re.search(r"internalField\s+uniform\s+([^;]+);", text)
    if m:
        val = m.group(1).strip()
        arr = np.array([float(v) for v in val.strip("()").split()])
        if n_cells is None:
            raise ValueError(f"{path}: uniform field, n_cells needed")
        return np.tile(arr, (n_cells, 1)).squeeze()
    m = re.search(r"internalField\s+nonuniform\s+List<(\w+)>\s*(\d+)\s*\(", text)
    if not m:
        raise ValueError(f"Cannot parse internalField in {path}")
    kind, n = m.group(1), int(m.group(2))
    body = text[m.end():]
    if kind == "scalar":
        vals = np.array(body.split(None, n)[:n], dtype=float)
        return vals
    nums = re.findall(r"\(([^()]*)\)", body[: body.find("\n)")])
    return np.array([[float(x) for x in v.split()] for v in nums[:n]])


def last_pressure_gradient(log):
    """Last pressure gradient reported by the meanVelocityForce fvOption."""
    hits = re.findall(r"pressure gradient = ([-+0-9.eE]+)", Path(log).read_text())
    if not hits:
        raise ValueError(f"No meanVelocityForce output in {log}")
    return float(hits[-1])


def pressure_gradient_history(log):
    return np.array([float(v) for v in re.findall(r"pressure gradient = ([-+0-9.eE]+)",
                                                  Path(log).read_text())])


def report(rows, tol):
    """Print a table of (name, computed, reference) and return True if all pass."""
    ok = True
    print(f"{'quantity':38s} {'OpenFOAM':>14s} {'analytical':>14s} {'rel. err':>10s}")
    for name, val, ref in rows:
        err = abs(val - ref)/max(abs(ref), 1e-300)
        flag = "" if err <= tol else "  <-- above tolerance"
        ok = ok and err <= tol
        print(f"{name:38s} {val:14.6g} {ref:14.6g} {err:10.3e}{flag}")
    return ok
